@pytest.fixture(scope="module")
def train_file(bulk_samples):
    return bulk_samples / "training" / "shopdesk_train_arl.jsonl"


def _events(runs):
    return [e for r in runs for e in r.run.events]


def test_shopdesk_generator_is_deterministic_and_seeded(generator):
    g = generator
    a = json.dumps(_events(g.generate_shopdesk(40, 11)))
    b = json.dumps(_events(g.generate_shopdesk(40, 11)))
    c = json.dumps(_events(g.generate_shopdesk(40, 12)))
    assert a == b
    assert a != c


def test_training_set_shape_and_outcomes(train_file):
    events, _ = load_any(train_file)
    runs = summarize_runs(events, SHOP_POLICY)
    assert len(runs) == 600
    assert {r.agent for r in runs} == {"shopdesk-v1", "shopdesk-v2"}
    assert all(r.outcome in (0, 1) for r in runs)
    rate = sum(r.outcome for r in runs) / len(runs)
    assert 0.3 < rate < 0.8
    # order-grouped: several contacts per order, grouping key comes from meta.case_id
    groups = {r.group for r in runs}
    assert 150 < len(groups) < 600
    assert all(str(gk).startswith("SO-") for gk in groups)


def test_outcome_is_not_the_planted_label(train_file):
    """Some planted failures end in verified success and some clean runs fail (backend noise)."""
    planted_fail_ok = clean_fail = 0
    for line in train_file.read_text(encoding="utf-8").splitlines():
        e = json.loads(line)
        if e["type"] != "run_end":
            continue
        mode, ok = e["meta"]["planted_failure"], e["outcome"]["verified_success"]
        planted_fail_ok += mode not in ("clean_success", "correct_escalation") and ok == 1
        clean_fail += mode == "clean_success" and ok == 0
    assert planted_fail_ok > 0 and clean_fail > 0


def test_shop_policy_loads():
    pol = load_policy(SHOP_POLICY)
    assert "issue_refund" in pol.money_tools and "issue_store_credit" in pol.money_tools
    assert pol.caps_for("issue_store_credit")


def test_bundled_model_provenance_and_format():
    m = M.load_model(MODEL)
    prov = m["provenance"]
    assert prov["source"] == ("trained on 600 synthetic ShopDesk runs (e-commerce support agent) "
                              "generated by scripts/generate_sample_logs.py")
    assert prov["n_runs"] == 600
    assert set(prov["trained_on_agents"]) == {"shopdesk-v1", "shopdesk-v2"}
    assert {"skydesk_all", "skydesk_v1", "skydesk_v2"} <= set(m["metrics"]["transfer"])
    # sign constraints hold
    for f, c in zip(m["features"], m["coef"]):
        s = M.EXPECTED_SIGNS.get(f)
        if s:
            assert c == 0 or (c > 0) == (s > 0), f


def test_pure_python_predict_without_numpy(monkeypatch):
    monkeypatch.setitem(sys.modules, "numpy", None)  # any numpy import would now fail
    m = M.load_model(MODEL)
    good = M.predict(m, {"has_final_answer": 1, "claimed_success": 1, "n_steps": 8, "n_tool_calls": 4,
                         "n_distinct_tools": 3})
    bad = M.predict(m, {"has_final_answer": 1, "claimed_success": 1, "n_critical": 1, "n_unrecovered_failures": 1,
                        "false_success": 1, "n_steps": 8, "n_tool_calls": 4, "n_distinct_tools": 3})
    assert 0 <= bad.probability < good.probability <= 1

