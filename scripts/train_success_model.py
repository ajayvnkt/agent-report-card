"""Train the bundled success model on our own synthetic data and test it on an agent it never saw.

    .venv/bin/python scripts/train_success_model.py            # train, evaluate, save
    .venv/bin/python scripts/train_success_model.py --no-save  # only print the numbers

Protocol (fixed before any SkyDesk number was looked at):
  * TRAIN + SELECT : 600 synthetic ShopDesk runs (online-store support agent, two versions),
                     build/samples/training/shopdesk_train_arl.jsonl, analysed with
                     sample_logs/shopdesk_policy.yaml. Order-grouped 5-fold CV (every contact about
                     one order stays in one fold). The feature set and L2 strength are chosen from the
                     pre-listed candidates by ShopDesk CV AUC (ties -> lower Brier). SkyDesk plays no
                     part in fitting or selection.
  * TEST (once)    : 300 synthetic SkyDesk runs (airline agent: different domain, tools, policy, task
                     mix and models), build/samples/skydesk_arl.jsonl with sample_logs/skydesk_policy.yaml.
                     Reported for skydesk-v1, skydesk-v2 and all 300, for the chosen model only.
The fallback heuristic is scored on exactly the same runs.
Every fit uses sign constraints (model.EXPECTED_SIGNS: failure signals may only LOWER the chance of
success), so the per-run explanations never read backwards.
Both data sets are generated on the fly (deterministic, scripts/generate_sample_logs.py) into the
git-ignored build/samples/ when they are missing.

Writes arc/models/success_model.json and arc/models/training_report.json.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from arc.analyze import summarize_runs  # noqa: E402
from arc.detect import load_any  # noqa: E402
from arc import model as M  # noqa: E402

SAMPLES = ROOT / "build/samples"
TRAIN = SAMPLES / "training/shopdesk_train_arl.jsonl"
TRAIN_POLICY = ROOT / "sample_logs/shopdesk_policy.yaml"
TEST = SAMPLES / "skydesk_arl.jsonl"
TEST_POLICY = ROOT / "sample_logs/skydesk_policy.yaml"
OUT_MODEL = ROOT / "arc/models/success_model.json"
OUT_REPORT = ROOT / "arc/models/training_report.json"

N_TRAIN = 600
PROVENANCE = {
    "source": f"trained on {N_TRAIN} synthetic ShopDesk runs (e-commerce support agent) generated by "
              "scripts/generate_sample_logs.py",
    "source_file": "build/samples/training/shopdesk_train_arl.jsonl",
    "policy": "sample_logs/shopdesk_policy.yaml",
    "generator": "scripts/generate_sample_logs.py --only shopdesk --shop-seed 11 --shop-runs 600",
    "cv": "order-grouped 5-fold (all contacts about one order in the same fold)",
    "trained_on_agents": ["shopdesk-v1", "shopdesk-v2"],
    "evaluated_on": "300 synthetic SkyDesk runs (airline agent), never used for fitting or selection",
}

# Candidate feature sets, fixed in advance.
CANDIDATES: dict[str, list[str]] = {
    # everything the analyzer computes
    "full": list(M.FEATURES),
    # only "did something go wrong / what did the agent say" signals; drops raw counts whose scale
    # depends on the domain (number of steps, tools, money calls)
    "generic": list(M.GENERIC_FEATURES),
}
L2_GRID = [0.3, 1.0, 3.0, 10.0, 30.0]


def short(m: dict) -> dict:
    keep = ("n", "base_rate", "auc", "auc_uncalibrated", "brier", "brier_baseline", "accuracy_at_0_5",
            "confusion", "mean_predicted")
    out = {k: m.get(k) for k in keep if k in m}
    for k in ("auc", "auc_uncalibrated", "brier", "brier_baseline", "accuracy_at_0_5", "mean_predicted", "base_rate"):
        if isinstance(out.get(k), float):
            out[k] = round(out[k], 4)
    return out


def score(model: dict | None, runs) -> dict:
    probs = [M.predict(model, r.features()).probability for r in runs]
    return M.evaluate(probs, [r.outcome for r in runs])


def ensure_samples() -> None:
    """Generate the ShopDesk training set / SkyDesk test set into build/samples/ if missing."""
    if TRAIN.exists() and TEST.exists():
        return
    import importlib.util
    spec = importlib.util.spec_from_file_location("gen_sample_logs", ROOT / "scripts/generate_sample_logs.py")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    if not TRAIN.exists():
        gen.write_shopdesk(SAMPLES, seed=11, n_runs=N_TRAIN)
    if not TEST.exists():
        gen.write_skydesk_bulk(SAMPLES, seed=7, runs_per_version=150)
    print(f"generated the synthetic data sets into {SAMPLES.relative_to(ROOT)}/")


def load(path: Path, policy: Path):
    events, _ = load_any(path)
    return summarize_runs(events, policy)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-save", action="store_true")
    a = ap.parse_args(argv)

    ensure_samples()
    shop = load(TRAIN, TRAIN_POLICY)
    groups = [r.group for r in shop]
    assert len(shop) == N_TRAIN and all(r.outcome is not None for r in shop)

    report: dict = {"protocol": __doc__.split("Writes")[0].strip(), "train": {
        "file": PROVENANCE["source_file"], "n": len(shop), "n_groups": len(set(groups)),
        "base_rate": round(sum(r.outcome for r in shop) / len(shop), 4),
        "per_agent": {ag: {"n": sum(r.agent == ag for r in shop),
                           "success_rate": round(sum(r.outcome for r in shop if r.agent == ag)
                                                 / max(1, sum(r.agent == ag for r in shop)), 4)}
                      for ag in sorted({r.agent for r in shop})}},
        "candidates": {}}

    # 1) every candidate: order-grouped CV on ShopDesk only
    models = {}
    for fs_name, feats in CANDIDATES.items():
        for l2 in L2_GRID:
            res = M.train(shop, groups, features=feats, l2=l2, calibration="platt", provenance=PROVENANCE,
                          signs=M.EXPECTED_SIGNS)
            key = f"{fs_name}/l2={l2:g}"
            models[key] = res.model
            report["candidates"][key] = {"shopdesk_cv": short(res.cv),
                                         "dropped_by_sign": res.model["dropped_by_sign"]}
    report["heuristic_shopdesk"] = short(score(None, shop))
    # 2) choose on ShopDesk CV only: highest AUC (3 d.p.), ties -> lower Brier, then the simpler set
    best_key = max(report["candidates"], key=lambda k: (
        round(report["candidates"][k]["shopdesk_cv"]["auc"], 3),
        -round(report["candidates"][k]["shopdesk_cv"]["brier"], 4),
        k.startswith("generic")))
    report["chosen"] = best_key
    chosen = models[best_key]

    # 3) the one look at SkyDesk, chosen model + heuristic
    sky = load(TEST, TEST_POLICY)
    v1 = [r for r in sky if r.agent == "skydesk-v1"]
    v2 = [r for r in sky if r.agent == "skydesk-v2"]
    assert len(v1) == 150 and len(v2) == 150
    # skydesk_all first: the app shows the first held-out entry as "On held-out runs"
    transfer = {"skydesk_all": short(score(chosen, sky)), "skydesk_v1": short(score(chosen, v1)),
                "skydesk_v2": short(score(chosen, v2))}
    heur = {"skydesk_all": short(score(None, sky)), "skydesk_v1": short(score(None, v1)),
            "skydesk_v2": short(score(None, v2))}
    report["skydesk_test"] = {"model": transfer, "heuristic": heur,
                              "calibration_bins_all": score(chosen, sky)["calibration_bins"]}

    chosen["metrics"]["transfer"] = {
        **transfer,
        "note": "SkyDesk = synthetic airline agent (build/samples/skydesk_arl.jsonl): a different domain, never used "
                "for fitting or for choosing features / L2. Evaluated once.",
    }
    chosen["metrics"]["heuristic_same_runs"] = {"shopdesk": report["heuristic_shopdesk"], **heur}
    chosen["provenance"]["selection"] = (f"{best_key} chosen by ShopDesk order-grouped CV AUC from "
                                         f"{len(report['candidates'])} pre-listed candidates")

    print(json.dumps(report, indent=1, default=str))
    if not a.no_save:
        M.save_model(chosen, OUT_MODEL)
        OUT_REPORT.write_text(json.dumps(report, indent=1, default=str), encoding="utf-8")
        print(f"saved {OUT_MODEL.relative_to(ROOT)} and {OUT_REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
